import type { ReactNode } from "react";
import type { Route } from "../core/router";
import { ComingSoon } from "../features/stubs";
import { HomePage } from "../features/home/HomePage";
import { MarketingPage, PricingPage, DirectoryPage } from "../features/marketing/MarketingPages";
import { PublicSitePage } from "../features/league/PublicSite";
import { MyLeaguePage } from "../features/league/MyLeaguePage";
import { TeamsPage, TeamPage } from "../features/teams/TeamsPages";
import { SchedulePage } from "../features/schedule/SchedulePage";
import { AcademyPage, CategoryPage, LessonPage, CurriculumPage } from "../features/academy/AcademyPages";
import { ParentAcademyPage, GuidePage } from "../features/parents/ParentPages";
import { PracticeGeneratorPage, PlanPage } from "../features/practice/PracticePages";
import { IQPage, IQLessonPage, QuizPage } from "../features/iq/IQPages";
import { AchievementsPage } from "../features/achievements/AchievementsPage";
import { CoachesPage, CoachPlannerPage, CoachTeamPage, CoachLibraryPage, VideoReviewPage, PitchingPage } from "../features/coaches/CoachPages";
import { MessagesPage } from "../features/messages/MessagesPage";
import { ResourcesPage, ResourcePage, GlossaryPage } from "../features/resources/ResourcePages";
import { AccountPage, PrivacyPage } from "../features/account/AccountPages";
import { RegisterPage, RegistrationStatusPage } from "../features/registration/RegistrationPages";
import { AdminRouter } from "../features/admin/AdminRouter";
import { CalculatorPrintPage } from "../features/admin/CalculatorPage";
import { PlatformPage } from "../features/platform/PlatformPage";
import { SearchPage } from "../features/search/SearchPage";
import { UmpirePage, VolunteerPage, PlayerPage, EventPage } from "../features/roles/RolePages";
import { DemoEntry } from "../features/auth/WelcomePage";
export function routeView(r: Route): { frame: "app" | "public" | "none"; element: ReactNode } {
  switch (r.name) {
    case "marketing": return { frame: "public", element: <MarketingPage /> };
    case "pricing": return { frame: "public", element: <PricingPage /> };
    case "directory": return { frame: "public", element: <DirectoryPage /> };
    case "site": return { frame: "public", element: <PublicSitePage slug={r.id ?? "dvyaa"} /> };
    case "demo": return { frame: "none", element: <DemoEntry /> };
    case "home": return { frame: "app", element: <HomePage /> };
    case "league": return { frame: "app", element: <MyLeaguePage section={r.id} /> };
    case "teams": return { frame: "app", element: <TeamsPage /> };
    case "team": return { frame: "app", element: <TeamPage id={r.id!} /> };
    case "player": return { frame: "app", element: <PlayerPage id={r.id!} /> };
    case "schedule": return { frame: "app", element: <SchedulePage /> };
    case "event": return { frame: "app", element: <EventPage id={r.id!} /> };
    case "academy": return { frame: "app", element: r.id ? <CategoryPage category={r.id} /> : <AcademyPage /> };
    case "lesson": return { frame: "app", element: <LessonPage id={r.id!} /> };
    case "curriculum": return { frame: "app", element: <CurriculumPage id={r.id} /> };
    case "parents": return { frame: "app", element: <ParentAcademyPage section={r.id} /> };
    case "guide": return { frame: "app", element: <GuidePage id={r.id!} /> };
    case "practice": return { frame: "app", element: <PracticeGeneratorPage preset={r.id} /> };
    case "practice-plan": return { frame: "app", element: <PlanPage id={r.id!} /> };
    case "iq": return { frame: "app", element: <IQPage /> };
    case "iq-lesson": return { frame: "app", element: <IQLessonPage id={r.id!} /> };
    case "iq-quiz": return { frame: "app", element: <QuizPage id={r.id ?? "mixed"} /> };
    case "achievements": return { frame: "app", element: <AchievementsPage /> };
    case "coaches": return { frame: "app", element: r.id === "planner" ? <CoachPlannerPage /> : r.id === "plans" ? <CoachLibraryPage /> : r.id === "video" ? <VideoReviewPage /> : r.id === "pitching" ? <PitchingPage /> : <CoachesPage section={r.id} /> };
    case "coaches-team": return { frame: "app", element: <CoachTeamPage id={r.id!} /> };
    case "messages": return { frame: "app", element: <MessagesPage /> };
    case "thread": return { frame: "app", element: <MessagesPage threadId={r.id} /> };
    case "resources": return { frame: "app", element: <ResourcesPage category={r.id} /> };
    case "resource": return { frame: "app", element: <ResourcePage id={r.id!} /> };
    case "glossary": return { frame: "app", element: <GlossaryPage /> };
    case "account": return { frame: "app", element: <AccountPage section={r.id} /> };
    case "privacy": return { frame: "app", element: <PrivacyPage /> };
    case "register": return { frame: "app", element: <RegisterPage /> };
    case "registration": return { frame: "app", element: <RegistrationStatusPage id={r.id!} /> };
    case "admin": if (r.id?.startsWith("calculator-print")) return { frame: "none", element: <CalculatorPrintPage code={r.id.startsWith("calculator-print-") ? r.id.slice("calculator-print-".length) : undefined} /> }; return { frame: "app", element: <AdminRouter sub={r.id} /> };
    case "platform": return { frame: "app", element: <PlatformPage section={r.id} /> };
    case "search": return { frame: "app", element: <SearchPage /> };
    case "umpire": return { frame: "app", element: <UmpirePage /> };
    case "volunteer": return { frame: "app", element: <VolunteerPage /> };
    case "about": return { frame: "public", element: <MarketingPage /> };
    default: return { frame: "app", element: <ComingSoon title={r.raw} /> };
  }
}
